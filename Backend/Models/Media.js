import mongoose from 'mongoose';
import { nanoid } from 'nanoid';

// Polymorphic media asset. A single Media document can belong to any owner
// domain (Client, Blog, Team, …) via ownerType + ownerId, and is the single
// source of truth for every image / video / document the studio manages.
const mediaSchema = new mongoose.Schema({
    // ---- Core identifiers ----
    mediaId: {
        type: String,
        unique: true,
        default: () => nanoid(),
        index: true
    },
    fileName: { type: String, required: true },        // safe, stored file name (== storageKey basename)
    originalFileName: { type: String },                 // what the user uploaded
    mimeType: { type: String },
    fileSize: { type: Number },                         // bytes
    checksum: { type: String },                         // client-computed hash (optional, dedupe/integrity)

    // ---- Polymorphic ownership ----
    ownerType: {
        type: String,
        enum: ['Client', 'Website', 'Blog', 'Review', 'Team', 'Brand', 'System'],
        default: 'System',
        required: true
    },
    // Kept as Mixed because owners span both ObjectId collections and string ids.
    ownerId: { type: mongoose.Schema.Types.Mixed, default: null },

    // ---- Taxonomy & attributes ----
    mediaType: {
        type: String,
        enum: ['Image', 'Video', 'Document', 'Animation'],
        default: 'Image',
        required: true
    },
    visibility: {
        type: String,
        enum: ['Public', 'Private'],
        default: 'Public'
    },
    // Draft      → session created, no bytes yet
    // Uploading  → parts are flowing to R2
    // Processing → bytes are in R2; derivatives/transcode queued
    // Ready      → every rendition exists and is servable
    // Archived   → superseded or deleted; objects reaped by gcArchivedMedia.js
    status: {
        type: String,
        enum: ['Draft', 'Uploading', 'Processing', 'Ready', 'Archived'],
        default: 'Draft',
        index: true
    },
    featured: { type: Boolean, default: false },

    // ---- Content metadata ----
    title: { type: String, trim: true },
    caption: { type: String, trim: true },
    description: { type: String, trim: true },
    altText: { type: String, trim: true },
    tags: [{ type: String, trim: true }],
    eventGroup: { type: String, trim: true, default: '' },
    width: { type: Number },
    height: { type: Number },
    duration: { type: Number },                         // seconds, for video
    aspectRatio: { type: Number },                      // width/height, for CLS-free boxes

    // ---- Adaptive delivery ----
    // Tiny (~20-30 char) base64 preview painted instantly while the full asset
    // streams in — the "blur-up" placeholder. Generated by sharp on ingest.
    blurDataURL: { type: String },
    dominantColor: { type: String },                    // hex, for solid placeholders

    // Multi-resolution IMAGE variants. With Cloudflare Image Resizing you rarely
    // need these (resize on the fly), but they're here for providers without it.
    imageVariants: [{
        label: { type: String },                        // 'thumb' | 'sm' | 'md' | 'lg' | 'xl'
        width: { type: Number },
        height: { type: Number },
        storageKey: { type: String },
        url: { type: String },
        bytes: { type: Number },
        format: { type: String },                       // 'avif' | 'webp' | 'jpeg'
    }],

    // VIDEO renditions. Delivery is progressive MP4 over HTTP range requests —
    // there is no HLS/DASH and no ABR. The ffmpeg worker produces:
    //   source → the uploaded master, kept for archive and full-screen playback
    //   web    → 720p re-encode, the default playback rendition
    //   loop   → short silent hero loop (~8s), used by the homepage carousel
    // `sourceUrl`/`webUrl`/`loopUrl` are denormalised so public routes never
    // have to scan the renditions array on every request.
    video: {
        posterUrl: { type: String },
        posterStorageKey: { type: String },
        // The base poster is a real object in the bucket, so its size has to be
        // recorded or any "total stored" figure under-reports by exactly this
        // much. Only the webp posterVariants carried a `bytes` before.
        posterBytes: { type: Number },
        posterVariants: [{
            label: { type: String },
            width: { type: Number },
            height: { type: Number },
            url: { type: String },
            storageKey: { type: String },
            bytes: { type: Number },
            format: { type: String },
        }],

        sourceUrl: { type: String },
        webUrl: { type: String },
        loopUrl: { type: String },

        renditions: [{
            role: { type: String, enum: ['source', 'web', 'loop'] },
            label: { type: String },
            width: { type: Number },
            height: { type: Number },
            bitrateKbps: { type: Number },
            durationSec: { type: Number },
            bytes: { type: Number },
            url: { type: String },
            storageKey: { type: String },
            // moov atom before mdat — without it a player cannot start until it
            // has located the moov, which defeats progressive playback.
            faststart: { type: Boolean },
            hasAudio: { type: Boolean },
        }],

        codec: { type: String },
        audioStripped: { type: Boolean, default: false },
    },

    // ---- Storage details ----
    // 'S3' remains only for assets not yet migrated off the legacy bucket.
    provider: {
        type: String,
        enum: ['S3', 'R2'],
        default: 'R2'
    },
    bucket: { type: String },
    storageKey: { type: String, required: true },       // object key inside the bucket
    publicUrl: { type: String },
    cdnUrl: { type: String },
    version: { type: Number, default: 1 },

    // ---- Replacement & lifecycle ----
    // Assets are never overwritten in place (that is what makes the immutable
    // cache header safe). Replacing one mints a new doc and points the old one
    // at it, to be reaped after `deleteAfter`.
    supersededBy: { type: mongoose.Schema.Types.ObjectId, ref: 'Media' },
    deleteAfter: { type: Date },

    // Worker bookkeeping, surfaced in the admin when a job fails.
    processing: {
        attempts: { type: Number, default: 0 },
        lastError: { type: String },
        startedAt: { type: Date },
    },

    // Original S3 key for assets migrated off the legacy bucket — lets the
    // dual-read resolver fall back while the migration settles.
    legacy: {
        s3Key: { type: String, index: true },
    },

    // ---- Audit ----
    uploadedBy: { type: String }                        // admin email / id from the session token
}, {
    timestamps: true,
    toJSON: { virtuals: true },
    toObject: { virtuals: true }
});

// Common query paths: "give me media for this owner", tag lookups, type filters.
mediaSchema.index({ ownerType: 1, ownerId: 1 });
mediaSchema.index({ mediaType: 1, status: 1 });
mediaSchema.index({ tags: 1 });
// One object key = one document. Missing before, so a retried ingest could
// silently create duplicates pointing at the same bytes.
mediaSchema.index({ storageKey: 1 }, { unique: true, sparse: true });
// Drives the worker's catch-up sweep for anything stuck in Processing.
mediaSchema.index({ status: 1, updatedAt: -1 });
// Full-text search backing the picker's search box.
mediaSchema.index({ title: 'text', altText: 'text', caption: 'text', tags: 'text' });

// Prefer the CDN url when present, else the public url.
mediaSchema.virtual('url').get(function () {
    return this.cdnUrl || this.publicUrl || '';
});

const Media = mongoose.models.Media || mongoose.model('Media', mediaSchema);
export default Media;
